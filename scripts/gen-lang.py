#!/usr/bin/env python3
"""Embeds res/lang/*.toml into src/hooks/lang.generated.h.

The .toml files are the checked-in source of truth; the header is a
gitignored build artifact (scripts/build.py runs this before the runner
build). The table is indexed like the DS firmware language codes DQ9 has
text for: 1 English, 2 French, 3 German, 4 Italian, 5 Spanish. A key a
language lacks is left null, and Tr() (src/hooks/lang.h) falls back to
English.
"""
import os
import sys
import tomllib

ROOT = os.path.normpath(os.path.join(os.path.dirname(os.path.abspath(__file__)), ".."))
LANG_DIR = os.path.join(ROOT, "res", "lang")
OUT_PATH = os.path.join(ROOT, "src", "hooks", "lang.generated.h")
CODES = ["en", "fr", "de", "it", "es", "ja"]  # DS language codes 1..5, then 6 = Japanese


def c_string(text, encoding="utf8"):
    # Octal escapes for anything outside printable ASCII: unlike \x they
    # stop after three digits, so a following character can't extend them.
    out = []
    for b in text.encode(encoding):
        if b in (0x22, 0x5C):
            out.append("\\" + chr(b))
        elif 0x20 <= b < 0x7F:
            out.append(chr(b))
        else:
            out.append(f"\\{b:03o}")
    return '"' + "".join(out) + '"'


def main():
    found = sorted(os.path.splitext(f)[0] for f in os.listdir(LANG_DIR) if f.endswith(".toml"))
    unknown = [c for c in found if c not in CODES]
    if unknown or "en" not in found:
        sys.exit(f"gen-lang: res/lang needs en.toml and only {CODES}; got {found}")

    langs = {}
    for code in found:
        with open(os.path.join(LANG_DIR, code + ".toml"), "rb") as f:
            langs[code] = tomllib.load(f)

    keys = [(sec, key) for sec, body in langs["en"].items() if isinstance(body, dict)
            for key in body]
    lines = [
        "#pragma once",
        "",
        "// Generated by scripts/gen-lang.py from res/lang/*.toml.",
        "",
        "namespace dq9 {",
        "",
        "struct LangText {",
        "    const char* section;",
        "    const char* key;",
        "    const char* text[6];  // en fr de it es (DS language codes 1..5), ja (6)",
        "};",
        "",
        "inline constexpr LangText kLangTexts[] = {",
    ]
    for sec, key in keys:
        texts = []
        for code in CODES:
            value = langs.get(code, {}).get(sec, {}).get(key)
            texts.append(c_string(value, "cp932" if code == "ja" else "utf8")
                         if isinstance(value, str) else "nullptr")
        lines.append(f'    {{"{sec}", "{key}", {{{", ".join(texts)}}}}},')
    lines += ["};", "", "}  // namespace dq9", ""]
    text = "\n".join(lines)

    try:
        with open(OUT_PATH, encoding="utf8") as f:
            if f.read() == text:
                return
    except FileNotFoundError:
        pass
    with open(OUT_PATH, "w", encoding="utf8", newline="\n") as f:
        f.write(text)
    print(f"+ wrote {OUT_PATH}")


if __name__ == "__main__":
    main()
